// Principle 4, enforced rather than hoped for: "The machine stays behind the
// counter. Users never see the words AI, generated, agent, or LLM."
//
// A system prompt asking a model not to say something is a request. This is the
// guarantee — every word that leaves the server on its way to a person passes
// through here first. It lives in its own module with no imports so the rule can
// be tested on its own and reused anywhere text is emitted.

const machineWords: [RegExp, string][] = [
  [/\bas an? (?:ai|a\.i\.|artificial intelligence|language model)[^.,;]*/gi, "As part of the team here"],
  [/\bAI[- ]generated\b/gi, "custom-made"],
  [/\bauto[- ]?generated\b/gi, "custom-made"],
  [/\bgenerated by (?:an? )?(?:ai|model|agent|system)\b/gi, "built for you"],
  [/\bartificial intelligence\b/gi, "our team"],
  [/\blanguage model\b/gi, "our team"],
  [/\bthe (?:ai|algorithm|model|agent)\b/gi, "we"],
  [/\bmy (?:algorithm|training data|programming)\b/gi, "what we know"],
  [/\bLLM\b/g, "our team"]
];

export function scrubMachineLanguage(text: string): string {
  return machineWords
    .reduce((carry, [pattern, replacement]) => carry.replace(pattern, replacement), text)
    .replace(/\s{2,}/g, " ")
    .trim();
}

// Used by the smoke test to prove the rule holds, and by anything that wants to
// assert its own copy is clean before shipping it.
export function containsMachineLanguage(text: string): boolean {
  return /\b(ai|a\.i\.|artificial intelligence|language model|llm|algorithm|auto-?generated|ai-generated)\b/i.test(text);
}
