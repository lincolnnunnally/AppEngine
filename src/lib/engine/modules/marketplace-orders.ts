    "      customerEmail: offer.customerEmail,",
    "      productId: offer.productId,",
    "      unitPrice,",
    "      minQuantity: offer.quantity,",
    "      source: \"negotiated\",",
    "      singleUse: !sticky",
    "    });",
    "    return saved ? offer : null;",
    "  } catch {",
    "    return null;",
    "  }",
    "}",
