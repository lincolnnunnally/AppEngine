    "    offeredUnitPrice: Number(row.offered_unit_price || 0),",
    "    counterUnitPrice: row.counter_unit_price != null ? Number(row.counter_unit_price) : null,",
    "    agreedUnitPrice: row.agreed_unit_price != null ? Number(row.agreed_unit_price) : null,",
    "    status: (String(row.status || \"pending\") as OfferStatus),",
    "    sticky: row.sticky === true || String(row.sticky) === \"true\",",
    "    message: String(row.message || \"\"),",
    "    createdAt: row.created_at ? String(row.created_at) : \"\"",
    "  };",
    "}",
    "",
    "export type CreateOfferInput = {",
    "  productId: string;",
    "  customerId: string | null;",
