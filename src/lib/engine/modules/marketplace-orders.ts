    "",
    "// Agree a price: the owner accepting the customer's offer, or the customer",
    "// accepting the owner's counter. Claimed in one update so it can only be agreed",
    "// once; the agreed price then becomes the customer's price for that product",
    "// from the offered quantity up (kept for future orders unless one-time).",
    "export async function agreeOffer(id: string, unitPrice: number, sticky: boolean): Promise<Offer | null> {",
    "  if (!hasDatabase() || !(unitPrice > 0)) return null;",
    "  try {",
    "    const sql = getDatabase();",
    "    const rows = await sql`",
