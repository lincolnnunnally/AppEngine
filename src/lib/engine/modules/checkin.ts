    "        count(*)::int as total,",
    "        count(*) filter (where is_first_time_visitor)::int as first_timers,",
    "        count(distinct nullif(person_email, ''))::int as unique_visitors,",
    "        count(*) filter (where contact_requested)::int as contact_requests",
    "      from checkin_records",
    "      where (${owner}::uuid is null or owner_id = ${owner})",
    "        and created_at >= now() - interval '30 days'`;",
    "    const totalSessions = Number(sessRows[0]?.n || 0);",
    "    const total = Number(chkRows[0]?.total || 0);",
    "    const firstTimers = Number(chkRows[0]?.first_timers || 0);",
    "    return {",
    "      totalSessions,",
    "      totalAttendance: total,",
    "      uniqueVisitors: Number(chkRows[0]?.unique_visitors || 0),",
    "      firstTimeVisitors: firstTimers,",
    "      returningVisitors: total - firstTimers,",
    "      averagePerSession: totalSessions ? Math.round((total / totalSessions) * 10) / 10 : 0,",
    "      contactRequests: Number(chkRows[0]?.contact_requests || 0),",
    "      firstTimerPercentage: total ? Math.round((firstTimers / total) * 1000) / 10 : 0",
    "    };",
    "  } catch {",
    "    return emptyStats;",
    "  }",
    "}",
    "",
    "export function checkinEnabled(): boolean {",
    '  return process.env.FEATURE_CHECKIN !== "false";',
    "}"
