// checkin — one job: open a session and check people in. Ported from
// ChurchConnect backend/routes/checkin.py: the check-in SESSION model (a unique
// 6-char code per service — create_checkin_session's random ascii+digits code —
// service_name/service_type/date/start_time/speaker/sermon_title, an is_active
// toggle, and the running attendance_count / first_time_visitors /
// returning_visitors / feedback_count stats), the individual CHECK-IN record
// (session_id, person name/email/phone, is_first_time_visitor derived by looking
// up a prior check-in for the same email at the same owner, how_heard,
// contact_requested/contact_reason), the public submit flow that bumps the
// session stats (+attendance, +first_time OR +returning), get_session_by_code
// (reject inactive sessions), toggle_session_active, and get_attendance_stats
// (last-30-days totals, unique visitors by email, first-timer %, avg/session).
// Staffing (roles, shifts, volunteer sign-up) is a different brick (`staffing`).
// Packs may snap both together. Events + booking a room stay on
// `events-scheduling` — that is one flow, two stages.
// Runs on the app owner's own database with graceful empty fallback,
// feature-flagged (FEATURE_CHECKIN); customers create sessions and check people
// in (rows scoped to user.id), and toggling a session is admin-gated.

import type { AppModule, GeneratedModuleFile } from "./types";

function file(path: string, lines: string[]): GeneratedModuleFile {
  return { path, content: lines.join("\n") + "\n" };
}

