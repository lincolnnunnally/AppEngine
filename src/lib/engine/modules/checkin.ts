    "  const url = new URL(request.url);",
    "  const ownerId = user?.id ? String(user.id) : undefined;",
    '  const activeOnly = url.searchParams.get("active") === "true";',
    "  const sessions = await listSessions(ownerId, activeOnly);",
    "  const stats = await getAttendanceStats(ownerId);",
    "  return NextResponse.json({ ok: true, sessions, stats });",
