    "      totalSessions: sessions.length,",
    "      totalAttendance: total,",
    "      uniqueVisitors: new Set(checkins.map((c) => c.personEmail).filter(Boolean)).size,",
    "      firstTimeVisitors: first,",
    "      returningVisitors: total - first,",
    "      averagePerSession: sessions.length ? Math.round((total / sessions.length) * 10) / 10 : 0,",
    "      contactRequests: checkins.filter((c) => c.contactRequested).length,",
    "      firstTimerPercentage: total ? Math.round((first / total) * 1000) / 10 : 0",
    "    };",
    "  }",
    "  try {",
