// staffing — one job: fill shifts. Roles, posted shifts, volunteer sign-up,
// and a schedule that flags short-handed rooms or uncleared people.
// Ported from ChurchConnect backend/routes/childcare_staffing.py:
//   DEFAULT_RATIOS (infant 1:4, toddler 1:5, preschool 1:7, pre_k 1:8,
//   elementary 1:10), staffing ROLES with clearance requirements
//   (requires_background_check / cpr / child_protection_training, min_age_to_serve),
//   SHIFTS (event_date, start/end time, room, role, slots_needed) that volunteers
//   self-sign-up for, the (shift,user) unique-signup guard + drop, and the
//   get_schedule composition (filled vs slots_needed, needs_more, uncleared_alert).
// Check-in is a different brick (`checkin`). Packs may snap both together.
// Events + booking a room stay on `events-scheduling` — that is one flow, two stages.

import type { AppModule, GeneratedModuleFile } from "./types";

function file(path: string, lines: string[]): GeneratedModuleFile {
  return { path, content: lines.join("\n") + "\n" };
}

