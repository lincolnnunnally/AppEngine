    "// uncleared_alert when a signed-up volunteer was not cleared at signup.",
    "export async function getSchedule(date: string, ownerId?: string): Promise<ScheduledShift[]> {",
    "  return composeSchedule(await listShifts(ownerId, date, date), ownerId);",
