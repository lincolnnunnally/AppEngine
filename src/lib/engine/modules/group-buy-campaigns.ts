// group-buy-campaigns — lock a shared buy so a group can order together.
// Mined from AppEngine group-buy (United Under God Connect).
//
// One job: someone starts a group buy (what, from whom, when the order locks),
// members join it with how many they want, and the organizer sees the shared
// order — who is in and the total — to place it. Joining closes on the lock date.

import type { AppModule, GeneratedModuleFile } from "./types";

function file(path: string, lines: string[]): GeneratedModuleFile {
  return { path, content: lines.join("\n") + "\n" };
}

function libFile(): GeneratedModuleFile {
  return file("src/lib/db/group-buy-campaigns.ts", [
    'import { getDatabase, hasDatabase } from "@/lib/db/client";',
    "",
    "export type GroupBuyCampaign = {",
    "  id: string;",
    "  title: string;",
    "  vendor: string;",
    "  lockDate: string;",
    "  notes: string;",
    "  createdBy: string;",
    "  createdAt: string;",
    "  locked: boolean;",
    "  members: number;",
    "  totalQuantity: number;",
    "  myQuantity: number;",
    "};",
    "",
    "export type GroupBuyCommitment = { name: string; email: string; quantity: number; note: string; joinedAt: string };",
    "",
    'export function group_buy_campaignsEnabled() { return process.env.FEATURE_GROUP_BUY !== "false"; }',
    "",
    "// The order locks at the end of the lock date (a plain YYYY-MM-DD). No date, or",
    "// one we can't read, means it stays open until the organizer sets one.",
    "export function isLocked(lockDate: string, now = new Date()): boolean {",
    "  const match = /^(\\d{4})-(\\d{2})-(\\d{2})$/.exec(lockDate.trim());",
    "  if (!match) return false;",
    "  const end = new Date(Date.UTC(Number(match[1]), Number(match[2]) - 1, Number(match[3]) + 1));",
    "  return now.getTime() >= end.getTime();",
    "}",
    "",
    "function campaign(r: Record<string, unknown>): GroupBuyCampaign {",
    '  const lockDate = String(r.lock_date ?? "");',
    "  return {",
    "    id: String(r.id),",
    '    title: String(r.title ?? ""),',
    '    vendor: String(r.vendor ?? ""),',
    "    lockDate,",
    '    notes: String(r.notes ?? ""),',
    '    createdBy: String(r.created_by ?? ""),',
    '    createdAt: String(r.created_at ?? ""),',
    "    locked: isLocked(lockDate),",
    "    members: Number(r.members ?? 0),",
    "    totalQuantity: Number(r.total_quantity ?? 0),",
    "    myQuantity: Number(r.my_quantity ?? 0)",
    "  };",
    "}",
    "",
    "export async function listGroupBuys(viewerId: string): Promise<GroupBuyCampaign[]> {",
    "  if (!hasDatabase()) return [];",
    "  const sql = getDatabase();",
    "  const me = viewerId || null;",
    "  const rows = await sql`",
    "    select c.id, c.title, c.vendor, c.lock_date, c.notes, c.created_by, c.created_at,",
    "      (select count(*) from group_buy_commitments k where k.campaign_id = c.id)::int as members,",
    "      (select coalesce(sum(k.quantity), 0) from group_buy_commitments k where k.campaign_id = c.id)::int as total_quantity,",
    "      (select coalesce(sum(k.quantity), 0) from group_buy_commitments k where k.campaign_id = c.id and k.user_id = ${me}::uuid)::int as my_quantity",
    "    from group_buy_campaigns c order by c.created_at desc limit 100`;",
    "  return rows.map(campaign);",
    "}",
    "",
    "export async function getGroupBuy(id: string, viewerId: string): Promise<GroupBuyCampaign | null> {",
    "  if (!hasDatabase()) return null;",
    "  const list = await listGroupBuys(viewerId);",
    "  return list.find((c) => c.id === id) ?? null;",
    "}",
    "",
    "export async function createGroupBuy(input: { title: string; vendor: string; lockDate: string; notes: string; createdBy: string }): Promise<string | null> {",
    "  if (!hasDatabase()) return null;",
    "  const sql = getDatabase();",
    "  const rows = await sql`insert into group_buy_campaigns (title, vendor, lock_date, notes, created_by) values (${input.title}, ${input.vendor}, ${input.lockDate}, ${input.notes}, ${input.createdBy || null}) returning id`;",
    "  return rows[0] ? String(rows[0].id) : null;",
    "}",
    "",
    "// Join (or change how many) — quantity 0 leaves the group buy.",
    "export async function setCommitment(input: { campaignId: string; userId: string; quantity: number; note: string }): Promise<void> {",
    "  const sql = getDatabase();",
    "  if (input.quantity <= 0) {",
    "    await sql`delete from group_buy_commitments where campaign_id = ${input.campaignId} and user_id = ${input.userId}`;",
    "    return;",
    "  }",
    "  await sql`insert into group_buy_commitments (campaign_id, user_id, quantity, note) values (${input.campaignId}, ${input.userId}, ${input.quantity}, ${input.note})",
    "    on conflict (campaign_id, user_id) do update set quantity = excluded.quantity, note = excluded.note, updated_at = now()`;",
    "}",
    "",
    "// The shared order, for the organizer: who is in and how many each.",
    "export async function listCommitments(campaignId: string): Promise<GroupBuyCommitment[]> {",
    "  if (!hasDatabase()) return [];",
    "  const sql = getDatabase();",
    "  const rows = await sql`select u.name, u.email, k.quantity, k.note, k.created_at from group_buy_commitments k join users u on u.id = k.user_id where k.campaign_id = ${campaignId} order by k.created_at asc`;",
    "  return rows.map((r) => ({",
    '    name: String(r.name ?? ""),',
    '    email: String(r.email ?? ""),',
    "    quantity: Number(r.quantity ?? 0),",
    '    note: String(r.note ?? ""),',
    '    joinedAt: String(r.created_at ?? "")',
    "  }));",
    "}"
  ]);
}

const UUID_RE = "/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i";

function apiFile(): GeneratedModuleFile {
  return file("src/app/api/group-buy/route.ts", [
    'import { NextResponse } from "next/server";',
    'import { getCurrentUser } from "@/lib/auth/session";',
    'import { canAccessCustomerArea } from "@/lib/auth/roles";',
    'import { listGroupBuys, createGroupBuy, group_buy_campaignsEnabled } from "@/lib/db/group-buy-campaigns";',
    'export const dynamic = "force-dynamic";',
    "export async function GET() {",
    '  if (!group_buy_campaignsEnabled()) return NextResponse.json({ ok: false, message: "This feature is turned off." }, { status: 404 });',
    "  const user = await getCurrentUser();",
    '  if (!canAccessCustomerArea(user?.role)) return NextResponse.json({ ok: false, message: "Please sign in." }, { status: 401 });',
    "  return NextResponse.json({ ok: true, records: await listGroupBuys(user?.id || \"\") });",
    "}",
    "export async function POST(request: Request) {",
    '  if (!group_buy_campaignsEnabled()) return NextResponse.json({ ok: false, message: "This feature is turned off." }, { status: 404 });',
    "  const user = await getCurrentUser();",
    '  if (!canAccessCustomerArea(user?.role) || !user?.id) return NextResponse.json({ ok: false, message: "Please sign in." }, { status: 401 });',
    "  const body = (await request.json().catch(() => ({}))) as Record<string, unknown>;",
    '  const text = (key: string) => (typeof body[key] === "string" ? (body[key] as string).trim() : "");',
    '  const title = text("title");',
    '  const lockDate = text("lockDate");',
    '  if (!title) return NextResponse.json({ ok: false, message: "Say what the group is buying." }, { status: 400 });',
    '  if (lockDate && !/^\\d{4}-\\d{2}-\\d{2}$/.test(lockDate)) return NextResponse.json({ ok: false, message: "Use a date like 2026-12-01 for the lock date." }, { status: 400 });',
    '  const id = await createGroupBuy({ title, vendor: text("vendor"), lockDate, notes: text("notes"), createdBy: user.id });',
    '  if (!id) return NextResponse.json({ ok: false, message: "Connect a database to save this." }, { status: 503 });',
    "  return NextResponse.json({ ok: true, id });",
    "}"
  ]);
}

function joinApiFile(): GeneratedModuleFile {
  return file("src/app/api/group-buy/[id]/join/route.ts", [
    'import { NextResponse } from "next/server";',
    'import { getCurrentUser } from "@/lib/auth/session";',
    'import { canAccessCustomerArea } from "@/lib/auth/roles";',
    'import { getGroupBuy, setCommitment, group_buy_campaignsEnabled } from "@/lib/db/group-buy-campaigns";',
    'export const dynamic = "force-dynamic";',
    "export async function POST(request: Request, { params }: { params: Promise<{ id: string }> }) {",
    '  if (!group_buy_campaignsEnabled()) return NextResponse.json({ ok: false, message: "This feature is turned off." }, { status: 404 });',
    "  const user = await getCurrentUser();",
    '  if (!canAccessCustomerArea(user?.role) || !user?.id) return NextResponse.json({ ok: false, message: "Please sign in." }, { status: 401 });',
    "  const { id } = await params;",
    `  if (!${UUID_RE}.test(id)) return NextResponse.json({ ok: false, message: "That group buy was not found." }, { status: 404 });`,
    "  const campaign = await getGroupBuy(id, user.id);",
    '  if (!campaign) return NextResponse.json({ ok: false, message: "That group buy was not found." }, { status: 404 });',
    '  if (campaign.locked) return NextResponse.json({ ok: false, message: "This order has locked — it is no longer taking changes." }, { status: 409 });',
    "  const body = (await request.json().catch(() => ({}))) as Record<string, unknown>;",
    "  const quantity = Math.floor(Number(body.quantity ?? 1));",
    '  if (!Number.isFinite(quantity) || quantity < 0 || quantity > 1000) return NextResponse.json({ ok: false, message: "Choose how many, from 0 to 1000." }, { status: 400 });',
    '  const note = typeof body.note === "string" ? body.note.trim().slice(0, 500) : "";',
    "  await setCommitment({ campaignId: id, userId: user.id, quantity, note });",
    "  return NextResponse.json({ ok: true, campaign: await getGroupBuy(id, user.id) });",
    "}"
  ]);
}

