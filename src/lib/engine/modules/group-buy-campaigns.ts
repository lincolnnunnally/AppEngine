function pageFile(): GeneratedModuleFile {
  return file("src/app/group-buy/page.tsx", [
    'import { requireCustomerAccess } from "@/lib/auth/session";',
    'import { canAccessAdmin } from "@/lib/auth/roles";',
    'import { listGroupBuys, listCommitments, group_buy_campaignsEnabled, type GroupBuyCommitment } from "@/lib/db/group-buy-campaigns";',
    'import { Form, JoinForm } from "./group-buy-campaigns-form";',
    'export const dynamic = "force-dynamic";',
    "export default async function Page() {",
    '  if (!group_buy_campaignsEnabled()) return (<main className="shell"><h1>Buy together</h1><p>This feature is turned off for this app.</p></main>);',
    '  const user = await requireCustomerAccess("/group-buy");',
    "  let campaigns: Awaited<ReturnType<typeof listGroupBuys>> = [];",
    "  let loadError = false;",
    "  try { campaigns = await listGroupBuys(user.id); } catch { loadError = true; }",
    "  const rosters: Record<string, GroupBuyCommitment[]> = {};",
    "  for (const c of campaigns) {",
    "    if (c.createdBy === user.id || canAccessAdmin(user.role)) rosters[c.id] = await listCommitments(c.id).catch(() => []);",
    "  }",
    "  return (",
    '    <main className="shell">',
    '      <p className="eyebrow">Group buy</p>',
    "      <h1>Buy together</h1>",
    "      <p>Name what the group is buying and when the order locks. Members join with how many they want; the organizer sees the whole order.</p>",
    "      <Form />",
    '      {loadError ? <p className="note" role="alert">Group buys could not be loaded right now.</p> : campaigns.length === 0 ? <p className="note">No group buys yet.</p> : (',
    '        <section className="panel-list">',
    "          {campaigns.map((c) => (",
    '            <article className="wide-card" key={c.id}>',
    "              <strong>{c.title}</strong>",
    "              <p>{c.vendor ? `From ${c.vendor}. ` : \"\"}{c.lockDate ? (c.locked ? `Locked on ${c.lockDate}.` : `Locks ${c.lockDate}.`) : \"No lock date yet.\"}</p>",
    "              {c.notes ? <p>{c.notes}</p> : null}",
    "              <p>{c.members} {c.members === 1 ? \"person\" : \"people\"} in · {c.totalQuantity} total</p>",
    "              {c.myQuantity > 0 ? <p><strong>You're in for {c.myQuantity}.</strong></p> : null}",
    "              {c.locked ? <p className=\"note\">This order has locked.</p> : <JoinForm id={c.id} joined={c.myQuantity} />}",
    "              {rosters[c.id] ? (",
    "                rosters[c.id].length === 0 ? <p className=\"note\">No one has joined yet.</p> : (",
    "                  <ul>",
    "                    {rosters[c.id].map((k) => (<li key={k.email}>{k.name && k.name !== k.email ? `${k.name} · ` : \"\"}{k.email} — {k.quantity}{k.note ? ` (${k.note})` : \"\"}</li>))}",
    "                  </ul>",
    "                )",
    "              ) : null}",
    "            </article>",
    "          ))}",
    "        </section>",
    "      )}",
    "    </main>",
    "  );",
    "}"
  ]);
}

function formFile(): GeneratedModuleFile {
  return file("src/app/group-buy/group-buy-campaigns-form.tsx", [
    '"use client";',
    'import { useState } from "react";',
    'import { useRouter } from "next/navigation";',
    "async function post(url: string, body: unknown) {",
    '  const response = await fetch(url, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(body) });',
    "  const json = await response.json().catch(() => ({}));",
    '  return response.ok && json.ok ? \"\" : String(json.message || "Could not save.");',
    "}",
    "export function Form() {",
    "  const router = useRouter();",
    '  const [status, setStatus] = useState<"idle" | "saving" | "error">("idle");',
    '  const [message, setMessage] = useState("");',
    "  async function submit(event: React.FormEvent<HTMLFormElement>) {",
    "    event.preventDefault();",
    "    const form = event.currentTarget;",
    '    setStatus("saving");',
    "    const data = new FormData(form);",
    '    const error = await post("/api/group-buy", { title: data.get("title"), vendor: data.get("vendor"), lockDate: data.get("lockDate"), notes: data.get("notes") });',
    '    if (error) { setStatus("error"); setMessage(error); return; }',
    "    form.reset();",
    '    setStatus("idle");',
    "    router.refresh();",
    "  }",
    "  return (",
    '    <form className="stack" onSubmit={submit}>',
    '      <input className="input" name="title" required placeholder="What we\'re buying" aria-label="What we\'re buying" />',
    '      <input className="input" name="vendor" placeholder="Vendor or source" aria-label="Vendor or source" />',
    '      <label className="stack">Order locks on<input className="input" type="date" name="lockDate" aria-label="Lock date" /></label>',
    '      <textarea className="input" name="notes" placeholder="Notes" aria-label="Notes" />',
    '      {status === "error" ? <p className="note" role="alert">{message}</p> : null}',
    '      <button className="button primary" type="submit" disabled={status === "saving"}>{status === "saving" ? "Saving…" : "Start a group buy"}</button>',
    "    </form>",
    "  );",
    "}",
    "export function JoinForm({ id, joined }: { id: string; joined: number }) {",
    "  const router = useRouter();",
    '  const [status, setStatus] = useState<"idle" | "saving" | "error">("idle");',
    '  const [message, setMessage] = useState("");',
    "  async function save(quantity: number) {",
    '    setStatus("saving");',
    "    const error = await post(`/api/group-buy/${id}/join`, { quantity });",
    '    if (error) { setStatus("error"); setMessage(error); return; }',
    '    setStatus("idle");',
    "    router.refresh();",
    "  }",
    "  function submit(event: React.FormEvent<HTMLFormElement>) {",
    "    event.preventDefault();",
    '    void save(Number(new FormData(event.currentTarget).get("quantity") || 1));',
    "  }",
    "  return (",
    '    <form className="stack" onSubmit={submit} aria-label="Join this group buy">',
    '      <input className="input" type="number" name="quantity" min={1} max={1000} defaultValue={joined || 1} aria-label="How many" />',
    '      {status === "error" ? <p className="note" role="alert">{message}</p> : null}',
    '      <button className="button primary" type="submit" disabled={status === "saving"}>{status === "saving" ? "Saving…" : joined ? "Change how many" : "Join this group buy"}</button>',
    '      {joined ? <button className="button" type="button" disabled={status === "saving"} onClick={() => void save(0)}>Leave</button> : null}',
    "    </form>",
    "  );",
    "}"
  ]);
}

