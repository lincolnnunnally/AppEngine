#!/usr/bin/env node
// Commit and push the growth-foundation files across every ecosystem repo.
//
// Deliberately stages an explicit file list rather than `git add -A`: these repos
// are shared with another agent and live under iCloud, so there is usually
// unrelated in-flight work in the tree that must not be swept into this commit.
//
//   node scripts/ship-growth-foundation.mjs           # dry run
//   node scripts/ship-growth-foundation.mjs --apply

import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ECOSYSTEM_APPS } from './lib/ecosystem-apps.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const WORKSPACE = resolve(HERE, '../../..');
const APPLY = process.argv.includes('--apply');

const MESSAGE = `feat(growth): first-party telemetry + SEO surface

Wire the shared LPL telemetry client so this app reports the ecosystem's
canonical funnel (page_view -> signup_started -> signup_completed ->
activated -> payment_completed) to the ecosystem-telemetry edge function,
and add a sitemap + robots policy so search engines have something to index.

Generated by app-engine:
  scripts/retrofit-telemetry.mjs
  scripts/add-seo-surface.mjs

Co-Authored-By: Claude Opus 5 <noreply@anthropic.com>`;

function git(cwd, args, allowFail = false) {
  try {
    return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  } catch (error) {
    if (allowFail) return null;
    throw new Error(`git ${args.join(' ')} failed: ${error.stderr || error.message}`);
  }
}

/** The files this build generates, in both the src/ and root layouts. */
function candidatePaths(app) {
  const base = app.base === '.' ? '' : `${app.base}/`;
  if (app.kind === 'next') {
    return [
      `${base}lib/telemetry.ts`,
      `${base}lib/TelemetryProvider.tsx`,
      `${base}app/layout.tsx`,
      `${base}app/sitemap.ts`,
      `${base}app/robots.ts`,
    ];
  }
  const ext = app.lang === 'js' ? 'js' : 'ts';
  return [
    `${base}lib/telemetry.${ext}`,
    `${base}lib/telemetry-spa.${ext}`,
    app.entry,
    'public/sitemap.xml',
    'public/robots.txt',
  ];
}

const results = [];
for (const app of ECOSYSTEM_APPS) {
  const root = join(WORKSPACE, app.dir);
  if (!existsSync(root)) {
    results.push({ slug: app.slug, status: 'skip', detail: 'not checked out' });
    continue;
  }

  // A repo may be nested (ChurchConnect/ChurchConnect); resolve its real root.
  const gitRoot = git(root, ['rev-parse', '--show-toplevel'], true);
  if (!gitRoot) {
    results.push({ slug: app.slug, status: 'no-git', detail: 'no git repo — deploy via CLI' });
    continue;
  }

  const paths = candidatePaths(app).filter((p) => existsSync(join(root, p)));
  // Stage paths relative to the git root, which differs from the app root when nested.
  const prefix = root === gitRoot ? '' : `${root.slice(gitRoot.length + 1)}/`;
  const staged = paths.map((p) => `${prefix}${p}`);

  const dirty = git(gitRoot, ['status', '--porcelain', '--', ...staged], true);
  if (!dirty) {
    results.push({ slug: app.slug, status: 'clean', detail: 'nothing to commit' });
    continue;
  }

  if (!APPLY) {
    results.push({ slug: app.slug, status: 'would', detail: `${staged.length} files` });
    continue;
  }

  try {
    const branch = git(gitRoot, ['rev-parse', '--abbrev-ref', 'HEAD']);
    git(gitRoot, ['add', '--', ...staged]);
    git(gitRoot, ['commit', '-m', MESSAGE]);

    const remote = git(gitRoot, ['remote'], true);
    if (!remote) {
      results.push({ slug: app.slug, status: 'local', detail: 'committed; no remote — deploy via CLI' });
      continue;
    }
    git(gitRoot, ['push', 'origin', branch]);
    results.push({ slug: app.slug, status: 'pushed', detail: `${branch} (${staged.length} files)` });
  } catch (error) {
    results.push({ slug: app.slug, status: 'error', detail: error.message.split('\n')[0].slice(0, 120) });
  }
}

console.log(APPLY ? '\nShipped:\n' : '\nDry run (pass --apply):\n');
for (const r of results) {
  const icon = { pushed: '+', would: '.', clean: '=', local: 'L', 'no-git': '!', skip: '-', error: 'x' }[r.status] ?? '?';
  console.log(`  ${icon} ${r.slug.padEnd(22)} ${r.status.padEnd(7)} ${r.detail}`);
}
const counts = results.reduce((a, r) => ({ ...a, [r.status]: (a[r.status] ?? 0) + 1 }), {});
console.log(`\n  ${Object.entries(counts).map(([k, v]) => `${k}: ${v}`).join('   ')}\n`);
if (counts.error) process.exitCode = 1;
