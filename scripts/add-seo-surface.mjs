#!/usr/bin/env node
// Give every ecosystem app a front door search engines can actually find.
//
// Before this, not one of the 21 apps had a sitemap or a robots policy, so
// Google had almost nothing to index. This emits, per app:
//
//   Next apps : app/sitemap.ts + app/robots.ts (typed, framework-native)
//   SPA apps  : public/sitemap.xml + public/robots.txt (no server to render them)
//
// Routes are discovered from the filesystem, so the sitemap reflects what the app
// really serves. Dynamic ([id]) and private (/admin, /account, …) routes are left
// out — dynamic ones need per-app data queries, which the growth loop adds later
// as programmatic SEO.
//
//   node scripts/add-seo-surface.mjs             # dry run
//   node scripts/add-seo-surface.mjs --apply
//   node scripts/add-seo-surface.mjs --apply --only furfriend

import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync, statSync } from 'node:fs';
import { dirname, join, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ECOSYSTEM_APPS, PRIVATE_ROUTE_PREFIXES, isPrivateRoute } from './lib/ecosystem-apps.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const WORKSPACE = resolve(HERE, '../../..');

const args = process.argv.slice(2);
const APPLY = args.includes('--apply');
const onlyIdx = args.indexOf('--only');
const ONLY = onlyIdx !== -1 && args[onlyIdx + 1] ? args[onlyIdx + 1].split(',').map((s) => s.trim()) : null;

const results = [];
const record = (slug, status, detail) => results.push({ slug, status, detail });

function write(path, content) {
  if (!APPLY) return;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content, 'utf8');
}

/** Every static, publicly-indexable route the app serves, discovered from disk. */
function discoverRoutes(appDir) {
  const routes = [];

  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name === 'node_modules' || entry.name.startsWith('_')) continue;
        walk(full);
      } else if (/^page\.(tsx|jsx|ts|js)$/.test(entry.name)) {
        const rel = relative(appDir, dir);
        // Route groups like (marketing) organise files but are not URL segments.
        const segments = rel.split('/').filter((s) => s && !(s.startsWith('(') && s.endsWith(')')));
        const route = '/' + segments.join('/');
        routes.push(route === '/' ? '/' : route.replace(/\/$/, ''));
      }
    }
  };

  walk(appDir);

  return [...new Set(routes)]
    .filter((r) => !r.includes('[')) // dynamic routes need data; handled by programmatic SEO
    .filter((r) => !isPrivateRoute(r))
    .sort((a, b) => (a === '/' ? -1 : b === '/' ? 1 : a.localeCompare(b)));
}

function priorityFor(route) {
  if (route === '/') return '1';
  return route.split('/').filter(Boolean).length === 1 ? '0.8' : '0.6';
}

function sitemapTs(app, routes) {
  return `import type { MetadataRoute } from 'next';

// Generated by app-engine: scripts/add-seo-surface.mjs
// Re-run that script after adding pages so search engines see them.
const BASE_URL = process.env.NEXT_PUBLIC_SITE_URL ?? '${app.url}';

const ROUTES: Array<{ path: string; priority: number }> = [
${routes.map((r) => `  { path: '${r}', priority: ${priorityFor(r)} },`).join('\n')}
];

export default function sitemap(): MetadataRoute.Sitemap {
  const lastModified = new Date();
  return ROUTES.map(({ path, priority }) => ({
    url: \`\${BASE_URL}\${path === '/' ? '' : path}\`,
    lastModified,
    changeFrequency: priority === 1 ? 'weekly' : 'monthly',
    priority,
  }));
}
`;
}

function robotsTs(app) {
  return `import type { MetadataRoute } from 'next';

// Generated by app-engine: scripts/add-seo-surface.mjs
const BASE_URL = process.env.NEXT_PUBLIC_SITE_URL ?? '${app.url}';

export default function robots(): MetadataRoute.Robots {
  return {
    rules: {
      userAgent: '*',
      allow: '/',
      // Private and per-user areas: no value in the index, and some leak state.
      disallow: [${PRIVATE_ROUTE_PREFIXES.map((p) => `'/${p}/'`).join(', ')}],
    },
    sitemap: \`\${BASE_URL}/sitemap.xml\`,
  };
}
`;
}

function sitemapXml(app, routes) {
  const today = new Date().toISOString().slice(0, 10);
  const urls = routes
    .map(
      (r) =>
        `  <url>\n    <loc>${app.url}${r === '/' ? '' : r}</loc>\n` +
        `    <lastmod>${today}</lastmod>\n    <priority>${priorityFor(r)}</priority>\n  </url>`,
    )
    .join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by app-engine: scripts/add-seo-surface.mjs -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`;
}

function robotsTxt(app) {
  return (
    `# Generated by app-engine: scripts/add-seo-surface.mjs\n` +
    `User-agent: *\nAllow: /\n` +
    PRIVATE_ROUTE_PREFIXES.map((p) => `Disallow: /${p}/`).join('\n') +
    `\n\nSitemap: ${app.url}/sitemap.xml\n`
  );
}

/**
 * A single-page SPA shell has no crawlable routes on disk, so fall back to the
 * home page rather than emitting an empty sitemap that tells Google nothing.
 */
function spaRoutes() {
  return ['/'];
}

for (const app of ECOSYSTEM_APPS) {
  if (ONLY && !ONLY.includes(app.slug)) continue;
  if (app.internal) {
    record(app.slug, 'skip', 'internal owner tool — deliberately not indexed');
    continue;
  }

  const root = join(WORKSPACE, app.dir);
  if (!existsSync(root)) {
    record(app.slug, 'skip', `repo not checked out at ${app.dir}`);
    continue;
  }

  try {
    if (app.kind === 'next') {
      const appDir = app.base === '.' ? join(root, 'app') : join(root, app.base, 'app');
      if (!existsSync(appDir) || !statSync(appDir).isDirectory()) {
        record(app.slug, 'skip', 'no app/ directory');
        continue;
      }
      const routes = discoverRoutes(appDir);
      if (routes.length === 0) {
        record(app.slug, 'skip', 'no public static routes found');
        continue;
      }
      write(join(appDir, 'sitemap.ts'), sitemapTs(app, routes));
      write(join(appDir, 'robots.ts'), robotsTs(app));
      record(app.slug, 'wrote', `${routes.length} routes → sitemap.ts + robots.ts`);
    } else {
      const routes = spaRoutes();
      write(join(root, 'public/sitemap.xml'), sitemapXml(app, routes));
      write(join(root, 'public/robots.txt'), robotsTxt(app));
      record(app.slug, 'wrote', `public/sitemap.xml + robots.txt (${routes.length} route)`);
    }
  } catch (error) {
    record(app.slug, 'error', error.message);
  }
}

console.log(APPLY ? '\nSEO surface written:\n' : '\nDry run (pass --apply to write):\n');
for (const r of results) {
  const icon = { wrote: '+', skip: '-', error: 'x' }[r.status] ?? '?';
  console.log(`  ${icon} ${r.slug.padEnd(22)} ${r.detail}`);
}
const counts = results.reduce((a, r) => ({ ...a, [r.status]: (a[r.status] ?? 0) + 1 }), {});
console.log(`\n  ${Object.entries(counts).map(([k, v]) => `${k}: ${v}`).join('   ')}\n`);
if (counts.error) process.exitCode = 1;
